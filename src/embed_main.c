#include <SDL3/SDL.h>

/*
 * smxembed writes a C file that defines `smx_game_rom` and
 * `smx_game_rom_size` from a ROM file, for builds with SMX_EMBED_ROM. The
 * file goes under the build tree and is never committed.
 */

/* Bytes per line of the generated array. */
#define SMX_EMBED_LINE 32u

int main(int argc, char **argv) {
  size_t size = 0;
  Uint8 *rom = NULL;
  SDL_IOStream *out = NULL;
  Uint32 at = 0;
  bool ok = true;

  if (argc != 3) {
    SDL_Log("usage: smxembed ROM OUT.c");
    return 1;
  }
  rom = (Uint8 *)SDL_LoadFile(argv[1], &size);
  if (rom == NULL || size == 0 || size > 8u * 1024u * 1024u) {
    SDL_Log("smxembed: cannot read %s", argv[1]);
    SDL_free(rom);
    return 1;
  }
  out = SDL_IOFromFile(argv[2], "wb");
  if (out == NULL) {
    SDL_Log("smxembed: cannot write %s: %s", argv[2], SDL_GetError());
    SDL_free(rom);
    return 1;
  }
  ok = SDL_IOprintf(out, "/* Generated by smxembed from the user's ROM. Do not commit. */\n"
                         "#include \"smx/game.h\"\n\n"
                         "static const Uint8 smx_game_rom_bytes[%u] = {\n",
                    (unsigned)size) > 0;
  for (; ok && at < (Uint32)size; at += SMX_EMBED_LINE) {
    char line[SMX_EMBED_LINE * 4u + 2u];
    Uint32 length = 0;
    Uint32 index = at;
    for (; index < at + SMX_EMBED_LINE && index < (Uint32)size; index += 1) {
      length += (Uint32)SDL_snprintf(line + length, sizeof(line) - length, "%u,",
                                     (unsigned)rom[index]);
    }
    line[length] = '\n';
    ok = SDL_WriteIO(out, line, length + 1u) == length + 1u;
  }
  ok = ok && SDL_IOprintf(out,
                          "};\n\nconst Uint8 *const smx_game_rom = smx_game_rom_bytes;\n"
                          "const Uint32 smx_game_rom_size = %uu;\n",
                          (unsigned)size) > 0;
  ok = SDL_CloseIO(out) && ok;
  SDL_free(rom);
  if (!ok) {
    SDL_Log("smxembed: cannot write %s", argv[2]);
    return 1;
  }
  return 0;
}
